BEGIN
  EXECUTE IMMEDIATE 'DROP TABLE payroll_compare_results PURGE';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE != -942 THEN RAISE; END IF;
END;
/

CREATE TABLE payroll_compare_results (
  compare_id      NUMBER        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_date        DATE          DEFAULT SYSDATE NOT NULL,
  run_id          VARCHAR2(50),
  -- Categorie: SETUP / MAATWERK / BEVEILIGING
  category        VARCHAR2(50)  NOT NULL,
  -- Object type: PAY_ELEMENTS / FAST_FORMULA_CODE / PLSQL_SOURCE / USERS / etc.
  object_type     VARCHAR2(100) NOT NULL,
  -- Soort verschil: LOKAAL_ALLEEN / PROD_ALLEEN / VERSCHIL
  difference_type VARCHAR2(20)  NOT NULL,
  object_name     VARCHAR2(500) NOT NULL,
  sub_object      VARCHAR2(500),
  local_value     VARCHAR2(4000),
  remote_value    VARCHAR2(4000),
  details         VARCHAR2(4000)
)
TABLESPACE USERS;

CREATE INDEX idx_pcr_run_id   ON payroll_compare_results (run_id);
CREATE INDEX idx_pcr_category ON payroll_compare_results (category, object_type);
CREATE INDEX idx_pcr_difftype ON payroll_compare_results (difference_type);

COMMIT;

